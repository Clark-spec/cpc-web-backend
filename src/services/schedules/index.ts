export const publishScheduleService = async (payload: any) => {
  try {
    if (payload && typeof payload.version === "number") {
      PUBLISHED_SCHEDULE = {
        ...PUBLISHED_SCHEDULE,
        ...payload,
        publishedAt: new Date().toISOString(),
      };
    }
    return {
      code: 200,
      status: "success",
      data: {
        schedule: PUBLISHED_SCHEDULE,
      },
    };
  } catch (error) {
    console.error("publishScheduleService Error:", error);
    return { code: 500, status: "error", message: "Failed to publish schedule" };
  }
};
